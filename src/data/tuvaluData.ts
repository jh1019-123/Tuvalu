/**
 * Rolls a random fish species strictly matching the requested tier probabilities:
 * 일반(Common): 30%, 드문(Uncommon): 30%, 에픽(Epic): 25%, 전설(Legendary): 10%, 신화(Mythic): 5%
 */
export function rollRandomFish(): FishSpecies {
  const r = Math.random();
  let tier: FishTier;
  if (r < 0.30) {
    tier = 'common';
  } else if (r < 0.60) {
    tier = 'uncommon';
  } else if (r < 0.85) {
    tier = 'epic';
  } else if (r < 0.95) {
    tier = 'legendary';
  } else {
    tier = 'mythic';
  }

  const pool = FISH_CATALOG.filter((f) => f.tier === tier);
  return pool[Math.floor(Math.random() * pool.length)];
}

